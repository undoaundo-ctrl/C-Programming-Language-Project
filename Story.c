#include <stdio.h>
#include <stdlib.h>

void pause_story(void)
{
    printf("\nPress ENTER to continue...");
    getchar();
}

void title(void)
{
    printf("============================================\n");
    printf("           THE LAST SIGNAL\n");
    printf("============================================\n\n");
}

void chapter1(void)
{
    printf("CHAPTER 1 - THE STRANGE NIGHT\n\n");

    printf("It was a quiet night in the small town of Northvale.\n");
    printf("The streets were empty, the shops were closed, and the\n");
    printf("only sound that could be heard was the distant wind.\n\n");

    printf("Alex sat beside his old computer, staring at the screen.\n");
    printf("He had been trying to repair a radio that he found in\n");
    printf("his grandfather's attic. The radio was extremely old,\n");
    printf("but something about it fascinated him.\n\n");

    printf("After several hours of work, Alex finally connected the\n");
    printf("last wire. He turned the radio on.\n\n");

    printf("At first, there was only static.\n");
    printf("Then something strange happened.\n\n");

    printf("The static suddenly stopped.\n");
    printf("A voice came through the speaker.\n\n");

    printf("\"If anyone can hear this... do not trust the tower.\"\n\n");

    printf("Alex froze.\n\n");

    printf("The message repeated itself three times.\n");
    printf("Then the radio became silent again.\n\n");

    printf("Alex looked out of the window.\n");
    printf("Far away, on top of the northern hill, stood an old\n");
    printf("communication tower that had been abandoned for years.\n\n");

    printf("Alex had never heard anyone talk about it.\n");
    printf("But now he had a reason to investigate.\n");

    pause_story();
}

void chapter2(void)
{
    printf("\nCHAPTER 2 - THE JOURNEY\n\n");

    printf("The next morning, Alex packed a backpack.\n");
    printf("He brought a flashlight, some food, a bottle of water,\n");
    printf("his repaired radio, and a small notebook.\n\n");

    printf("His friend Sam noticed the backpack.\n\n");

    printf("\"Where are you going?\" Sam asked.\n\n");

    printf("\"The northern hill,\" Alex replied.\n\n");

    printf("Sam immediately became interested.\n");
    printf("The two friends had grown up hearing stories about the\n");
    printf("abandoned tower, although nobody knew who built it.\n\n");

    printf("They started walking after lunch.\n");
    printf("The road slowly disappeared behind them as they entered\n");
    printf("the forest.\n\n");

    printf("For almost an hour, nothing unusual happened.\n");
    printf("Birds flew between the trees, leaves moved in the wind,\n");
    printf("and sunlight passed through the branches.\n\n");

    printf("Then the radio turned on by itself.\n\n");

    printf("KRRRRRRRRRR...\n\n");

    printf("Alex grabbed it.\n\n");

    printf("\"Hello?\" he said.\n\n");

    printf("A voice answered.\n\n");

    printf("\"You should not have come here.\"\n\n");

    printf("Sam looked at Alex.\n\n");

    printf("\"Did you hear that?\"\n\n");

    printf("\"Yeah.\"\n\n");

    printf("They continued walking anyway.\n\n");

    printf("Eventually, they reached the top of the hill.\n");
    printf("The tower stood before them, surrounded by tall grass.\n");
    printf("Its metal structure disappeared into the clouds.\n\n");

    printf("At the bottom was a small steel door.\n\n");

    printf("Alex pushed it.\n\n");

    printf("CLANK.\n\n");

    printf("The door opened.\n");

    pause_story();
}

void chapter3(void)
{
    printf("\nCHAPTER 3 - UNDERGROUND\n\n");

    printf("Inside the tower was a narrow staircase leading down.\n\n");

    printf("\"That makes no sense,\" Sam whispered.\n\n");

    printf("The tower was supposed to be abandoned, yet the stairs\n");
    printf("looked recently used.\n\n");

    printf("Alex turned on his flashlight.\n");
    printf("They slowly walked downward.\n\n");

    printf("After several minutes, they reached a huge underground\n");
    printf("room filled with old computers.\n\n");

    printf("Most of the machines were covered in dust.\n");
    printf("But one computer was still running.\n\n");

    printf("Its screen displayed a single message:\n\n");

    printf("SYSTEM STATUS: WAITING FOR CONNECTION\n\n");

    printf("Alex approached the keyboard.\n\n");

    printf("\"Maybe this is where the radio signal came from.\"\n\n");

    printf("He pressed a key.\n\n");

    printf("The screen changed.\n\n");

    printf("WELCOME, ALEX.\n\n");

    printf("Alex stepped backward.\n\n");

    printf("\"How does it know my name?\"\n\n");

    printf("Suddenly, every computer in the room turned on.\n\n");

    printf("The screens filled with numbers.\n");
    printf("Then a map appeared.\n\n");

    printf("The map showed Northvale.\n");

    printf("A red circle appeared around the town.\n\n");

    printf("Sam stared at the screen.\n\n");

    printf("\"Alex... I think something is coming.\"\n\n");

    printf("A countdown appeared.\n\n");

    printf("10...\n");
    printf("9...\n");
    printf("8...\n");
    printf("7...\n\n");

    printf("Alex searched the room for a way to stop it.\n");

    printf("Behind the computers, he discovered a large switch.\n");
    printf("Above it was a label:\n\n");

    printf("EMERGENCY SIGNAL SHUTDOWN\n\n");

    printf("He reached for the switch.\n\n");

    printf("3...\n");
    printf("2...\n");
    printf("1...\n\n");

    printf("Alex pulled it down.\n\n");

    printf("Everything went dark.\n");

    pause_story();
}

void chapter4(void)
{
    printf("\nCHAPTER 4 - THE TRUTH\n\n");

    printf("For several seconds, neither Alex nor Sam moved.\n\n");

    printf("Then a small emergency light turned on.\n\n");

    printf("The computer screen displayed one final message.\n\n");

    printf("CONNECTION TERMINATED.\n\n");

    printf("Alex found a folder beside the computer.\n");
    printf("Inside was an old notebook.\n\n");

    printf("The notebook explained everything.\n\n");

    printf("Decades earlier, scientists had built the tower as part\n");
    printf("of an experiment designed to communicate with satellites.\n");
    printf("But something went wrong.\n\n");

    printf("The system began receiving a signal that nobody could\n");
    printf("identify.\n\n");

    printf("The scientists tried to shut it down.\n");
    printf("They failed.\n\n");

    printf("Eventually, the facility was abandoned.\n\n");

    printf("The strange voice on the radio was actually an automated\n");
    printf("warning system created by one of the scientists.\n\n");

    printf("It had been waiting for someone to discover the facility.\n\n");

    printf("Alex looked at the radio.\n\n");

    printf("\"So the warning was real.\"\n\n");

    printf("Sam nodded.\n\n");

    printf("\"And we stopped it.\"\n\n");

    printf("Alex wasn't completely convinced.\n\n");

    printf("They climbed back to the surface.\n");

    printf("When they reached the top of the hill, the sky was filled\n");
    printf("with stars.\n\n");

    printf("For the first time that night, the radio was silent.\n\n");

    printf("They began walking home.\n");

    pause_story();
}

void ending(void)
{
    printf("\nFINAL CHAPTER - THE LAST SIGNAL\n\n");

    printf("Alex and Sam returned to Northvale before midnight.\n");
    printf("Nobody noticed that anything had happened.\n\n");

    printf("Alex placed the radio on his desk.\n");
    printf("He decided that he would never turn it on again.\n\n");

    printf("But just before he went to sleep, something happened.\n\n");

    printf("The radio clicked.\n\n");

    printf("Alex slowly turned around.\n\n");

    printf("The speaker produced a tiny burst of static.\n\n");

    printf("KRRR...\n\n");

    printf("Then a voice whispered:\n\n");

    printf("\"Thank you for shutting down the tower.\"\n\n");

    printf("Alex stared at the radio.\n\n");

    printf("The voice continued.\n\n");

    printf("\"But there are twelve more.\"\n\n");

    printf("The radio switched off.\n\n");

    printf("Alex stood silently in the darkness.\n\n");

    printf("Outside his window, twelve distant lights appeared on\n");
    printf("the horizon.\n\n");

    printf("One by one, they began to glow.\n\n");

    printf("Alex opened his notebook.\n");
    printf("He wrote a single sentence:\n\n");

    printf("\"This isn't the end. It's the beginning.\"\n\n");

    printf("THE END...?\n\n");

    printf("============================================\n");
    printf("             THE LAST SIGNAL\n");
    printf("============================================\n");
}

int main(void)
{
    title();
    chapter1();
    chapter2();
    chapter3();
    chapter4();
    ending();

    return 0;
}
